import { buildSync } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const repoRoot = process.cwd();
const outDir = path.join(repoRoot, ".tmp");
const outFile = path.join(outDir, "seo-prerender-bundle.cjs");
const manifestFile = path.join(repoRoot, "public", "seo-prerender.json");

mkdirSync(outDir, { recursive: true });

buildSync({
  entryPoints: [path.join(repoRoot, "scripts", "seo-prerender-entry.ts")],
  bundle: true,
  platform: "node",
  format: "cjs",
  outfile: outFile,
  logLevel: "silent",
});

const mod = await import(pathToFileURL(outFile).href);
const comparisons = mod.COMPARISON_PAGES ?? [];
const seoPages = mod.SEO_PAGES ?? [];

const record = {};
const updatedAt = "2026-05-27";

for (const page of comparisons) {
  for (const [p, locale] of [
    [page.path, "en"],
    [page.pathFr, "fr"],
  ]) {
    record[p] = {
      kind: "comparison",
      locale,
      pair: locale === "en" ? page.pathFr : page.path,
      slugKey: page.slugKey,
      title: locale === "fr" ? page.titleFr : page.titleEn,
      description: locale === "fr" ? page.descriptionFr : page.descriptionEn,
      h1: locale === "fr" ? page.h1Fr : page.h1En,
      verdict: locale === "fr" ? page.verdictFr : page.verdictEn,
      updatedAt: page.updatedAt,
      keywords: page.keywords,
      matrix: page.matrix.map((row) => ({
        label: locale === "fr" ? row.labelFr : row.labelEn,
        values: page.columns.map((col) => ({
          name: locale === "fr" ? col.labelFr : col.labelEn,
          value: row.values[col.id] ?? "—",
          highlight: Boolean(col.highlight),
        })),
      })),
      faq: (locale === "fr" ? page.faqFr : page.faqEn).map((f) => ({ q: f.q, a: f.a })),
    };
  }
}

for (const page of seoPages) {
  for (const [p, locale] of [
    [page.path, "en"],
    [page.pathFr, "fr"],
  ]) {
    record[p] = {
      kind: "landing",
      locale,
      pair: locale === "en" ? page.pathFr : page.path,
      slugKey: page.slugKey,
      title: locale === "fr" ? page.titleFr : page.titleEn,
      description: locale === "fr" ? page.descriptionFr : page.descriptionEn,
      h1: locale === "fr" ? page.h1Fr : page.h1En,
      lead: locale === "fr" ? page.leadFr : page.leadEn,
      bullets: locale === "fr" ? page.bulletsFr : page.bulletsEn,
      updatedAt,
      keywords: page.keywords,
      faq: (locale === "fr" ? page.faqFr : page.faqEn).map((f) => ({ q: f.q, a: f.a })),
    };
  }
}

writeFileSync(manifestFile, `${JSON.stringify({ generatedAt: new Date().toISOString(), pages: record }, null, 2)}\n`, "utf8");

const seoPaths = seoPages.flatMap((p) => [p.path, p.pathFr]);
const comparisonPaths = comparisons.flatMap((p) => [p.path, p.pathFr]);
const routePathsFile = path.join(repoRoot, "src", "generated", "marketingRoutePaths.ts");
mkdirSync(path.dirname(routePathsFile), { recursive: true });
writeFileSync(
  routePathsFile,
  `/** Auto-generated by scripts/generate-seo-prerender.mjs — do not edit manually */\n\nexport const SEO_PAGE_PATHS = ${JSON.stringify(seoPaths, null, 2)} as const;\n\nexport const COMPARISON_PAGE_PATHS = ${JSON.stringify(comparisonPaths, null, 2)} as const;\n\nexport const SEO_PAGE_PATH_SET: ReadonlySet<string> = new Set(SEO_PAGE_PATHS);\n\nexport const COMPARISON_PAGE_PATH_SET: ReadonlySet<string> = new Set(COMPARISON_PAGE_PATHS);\n`,
  "utf8",
);

console.log(`generate-seo-prerender: ${Object.keys(record).length} URLs → public/seo-prerender.json`);
console.log(`generate-seo-prerender: ${seoPaths.length + comparisonPaths.length} route paths → src/generated/marketingRoutePaths.ts`);
