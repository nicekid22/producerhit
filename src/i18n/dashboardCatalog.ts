export type DashboardMessages = { [K in keyof typeof DASHBOARD]: string };

export function buildDashboardSection(locale: AppLocale): DashboardMessages {
  return resolveSection(DASHBOARD, locale);
}

export function genreSelectionHintI18n(
  genre: string,
  locale: AppLocale,
  ideaFilled: boolean,
  lastRandom?: string,
  isFromIdea?: (v: string | null | undefined) => boolean,
  isRandom?: (v: string | null | undefined) => boolean,
): string {
  const d = buildDashboardSection(locale);
  const fromIdea = isFromIdea ?? ((v) => !v || v === "Auto");
  const random = isRandom ?? ((v) => v === "__random__");

  if (fromIdea(genre)) {
    return ideaFilled ? d.genreHintFromIdeaFilled : d.genreHintFromIdeaEmpty;
  }
  if (random(genre)) {
    if (ideaFilled) return d.genreHintRandomIdeaFilled;
    if (lastRandom) {
      return `${d.genreHintRandomLastPrefix}${lastRandom}${d.genreHintRandomRolledSuffix}`;
    }
    return d.genreHintRandomDefault;
  }
  return `${d.genreHintFixedPrefix}${genre}${d.genreHintFixedSuffix}`;
}

export function dashFmt(locale: AppLocale, key: keyof typeof DASHBOARD, ...parts: string[]): string {
  return pickL(DASHBOARD[key], locale) + parts.join("");
}
