export function musicMoneyPlaysI18n(locale: AppLocale, perTrack: string) {
  const vars = { perTrack };
  return PLAY_ORDER.map((id) => {
    const play = PLAYS[id];
    const potential =
      id === "beatstars"
        ? POTENTIAL
        : id === "youtube"
          ? "$500–$3k / mo"
          : id === "clients"
            ? "$80–$400 / client"
            : id === "sync"
              ? "$200–$5k / deal"
              : id === "streaming"
                ? "Royalties + discovery"
                : "$49–$199 / pack";
    const plan =
      id === "clients" ? "Studio" : id === "stems" ? "Plus" : "Pro";
    return {
      id,
      title: pickL(play.title, locale),
      potential,
      steps: play.steps.map((s) => interpolate(pickL(s, locale), vars)),
      plan,
    };
  });
}
