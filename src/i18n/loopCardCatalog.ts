export type LoopCardMessages = { [K in keyof typeof LOOP_CARD]: string };

export function buildLoopCardSection(locale: AppLocale): LoopCardMessages {
  return resolveSection(LOOP_CARD, locale);
}

export function loopCardCoverRerollAria(locale: AppLocale, cost: number): string {
  return pickL(LOOP_CARD.coverRerollAria, locale).replace("{cost}", String(cost));
}

export function loopCardVoiceCloneLabel(info: LoopVoiceCloneInfo | null, locale: AppLocale): string | null {
  if (!info) return null;
  const lc = buildLoopCardSection(locale);
  if (info.applied && !info.fallback) {
    const name = info.profileName?.trim();
    return name ? `${pickL(LOOP_CARD.voiceCloneAppliedNamed, locale)}${name}` : lc.voiceCloneApplied;
  }
  if (info.fallback) return lc.voiceCloneFallback;
  return null;
}
