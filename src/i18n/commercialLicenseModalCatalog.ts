export function buildCommercialLicenseModalCopy(locale: AppLocale) {
  const t = (key: keyof typeof COPY) => pickL(COPY[key], locale);
  return {
    title: t("title"),
    close: t("close"),
    certificateHint: t("certificateHint"),
    optionalLegalName: t("optionalLegalName"),
    settingsLink: t("settingsLink"),
    upgradeRequired: t("upgradeRequired"),
    downloadHint: t("downloadHint"),
    printPdf: t("printPdf"),
    printTip: t("printTip"),
    subtitle: (trackTitle: string, exportKind: "stems" | "wav" | string) =>
      i(pickL(exportKind === "stems" ? COPY.subtitleStems : COPY.subtitleTrack, locale), { title: trackTitle }),
  };
}
