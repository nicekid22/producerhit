const LOCALE_FIELD_SUFFIX: Record<AppLocale, string> = {
  en: "En",
  fr: "Fr",
  es: "Es",
  pt: "Pt",
  de: "De",
  it: "It",
  nl: "Nl",
  ar: "Ar",
  ja: "Ja",
  ko: "Ko",
  tr: "Tr",
  hi: "Hi",
  zh: "Zh",
  th: "Th",
};

function pickCollectionField(
  collection: LibraryCollection,
  base: "title" | "subtitle",
  locale: AppLocale,
): string {
  const key = `${base}${LOCALE_FIELD_SUFFIX[locale]}` as keyof LibraryCollection;
  const localized = collection[key];
  if (typeof localized === "string" && localized.length > 0) return localized;
  return collection[`${base}En`];
}

