function i(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function buildLandingGeneratorCopy(locale: AppLocale) {
  const count = PLAN_LIMITS.free;
  return {
    play: pickL(COPY.play, locale),
    pause: pickL(COPY.pause, locale),
    noCardCancel: pickL(COPY.noCardCancel, locale),
    describeIdea: pickL(COPY.describeIdea, locale),
    freeLabel: i(pickL(COPY.freeGenerationsMonth, locale), { count }),
    headlineSong: pickL(COPY.headlineSong, locale),
    headlineBeat: pickL(COPY.headlineBeat, locale),
    subSong: pickL(COPY.subSong, locale),
    subBeat: pickL(COPY.subBeat, locale),
    generatorEyebrow: pickL(COPY.generatorEyebrow, locale),
    artistStyle: pickL(COPY.artistStyle, locale),
    creationType: pickL(COPY.creationType, locale),
    advanced: pickL(COPY.advanced, locale),
    enterHint: pickL(COPY.enterHint, locale),
    playAria: (title: string) => `${pickL(COPY.play, locale)} ${title}`,
    pauseAria: (title: string) => `${pickL(COPY.pause, locale)} ${title}`,
    headline: (mode: "song" | "beat") =>
      mode === "song" ? pickL(COPY.headlineSong, locale) : pickL(COPY.headlineBeat, locale),
    sub: (mode: "song" | "beat") =>
      mode === "song" ? pickL(COPY.subSong, locale) : pickL(COPY.subBeat, locale),
  };
}
