export type RemixStudioMessages = { [K in keyof typeof REMIX_STUDIO]: string };

export function buildRemixStudioSection(locale: AppLocale): RemixStudioMessages {
  return resolveSection(REMIX_STUDIO, locale);
}

export type RemixVibeCopy = {
  panelTitle: string;
  panelHint: string;
  loadedToast: string;
  styleTouchLabel: string;
  styleTouchPlaceholder: string;
  ctaIdle: string;
  ctaGenerating: string;
  successToast: string;
  inspiredBy: (name: string) => string;
};

export function getRemixVibeCopy(locale: AppLocale): RemixVibeCopy {
  const rx = buildRemixStudioSection(locale);
  return {
    panelTitle: rx.vibePanelTitle,
    panelHint: rx.vibePanelHint,
    loadedToast: rx.vibeLoadedToast,
    styleTouchLabel: rx.vibeStyleTouchLabel,
    styleTouchPlaceholder: rx.vibeStyleTouchPlaceholder,
    ctaIdle: rx.runRemix,
    ctaGenerating: rx.vibeCtaGenerating,
    successToast: rx.vibeSuccessToast,
    inspiredBy: (name: string) => pickL(REMIX_STUDIO.inspiredByTemplate, locale).replace("{name}", name),
  };
}

export function remixPromptFallback(genre: string, locale: AppLocale): string {
  return pickL(REMIX_STUDIO.remixPromptFallback, locale).replace("{genre}", genre);
}
