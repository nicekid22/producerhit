export function buildUpsellCopy(
  reason: UpsellReason,
  locale: AppLocale,
  plan: string,
  ctx: UpsellContext = { source: "unknown" },
): UpsellCopy {
  const cur = normalizePlanId(plan);
  const target = recommendedUpgradePlan(plan);
  const remaining = ctx.remaining ?? 0;
  const baseLimit = getPlanBaseLimit(cur);
  const proLimit = PLAN_LIMITS.pro;
  const studioLimit = PLAN_LIMITS.studio;
  const plusLimit = PLAN_LIMITS.plus;

  if (reason === "feature_wav_format") {
    return {
      title: t(R.featureWavFormat.title, locale),
      description: t(R.featureWavFormat.description, locale),
      bullets: [
        genPerMonth(locale, proLimit),
        t(R.featureWavFormat.bulletToggle, locale),
        t(R.featureWavFormat.bulletCommercial, locale),
        planPriceUpsellLabel("pro", locale),
      ],
      primaryLabel: goProLabel(locale),
      secondaryLabel: t(R.featureWavFormat.secondary, locale),
      targetPlan: "pro",
    };
  }

  if (reason === "wav_export") {
    return {
      title: t(R.wavExport.title, locale),
      description: t(R.wavExport.description, locale),
      bullets: [
        t(R.wavExport.bulletPresets, locale),
        t(R.wavExport.bulletExport, locale),
        t(R.wavExport.bulletApply, locale),
        genPerMonthStudio(locale, studioLimit),
      ],
      primaryLabel: t(C.goStudio, locale),
      secondaryLabel: t(C.comparePlans, locale),
      targetPlan: "studio",
    };
  }

  if (reason === "feature_dual_generation") {
    return {
      title: t(R.featureDualGeneration.title, locale),
      description: t(R.featureDualGeneration.description, locale),
      bullets: [
        genPerMonthStudio(locale, studioLimit),
        t(R.featureDualGeneration.bulletParallel, locale),
        t(R.wavExport.bulletExport, locale),
        t(R.featureDualGeneration.bulletAllPro, locale),
      ],
      primaryLabel: t(C.goStudio, locale),
      secondaryLabel: t(R.featureDualGeneration.secondary, locale),
      targetPlan: "studio",
    };
  }

  if (reason === "feature_voice_to_song") {
    return {
      title: t(R.featureVoiceToSong.title, locale),
      description: t(R.featureVoiceToSong.description, locale),
      bullets: [
        t(R.featureVoiceToSong.bulletMic, locale),
        t(R.featureVoiceToSong.bulletTranscript, locale),
        t(R.featureVoiceToSong.bulletUnlimited, locale),
        genPerMonthStudio(locale, studioLimit),
      ],
      primaryLabel: t(C.goStudio, locale),
      secondaryLabel: t(R.featureVoiceToSong.keepTrial, locale),
      targetPlan: "studio",
    };
  }

  if (reason === "feature_voice_clone") {
    return {
      title: t(R.featureVoiceClone.title, locale),
      description: t(R.featureVoiceClone.description, locale),
      bullets: [
        t(R.featureVoiceClone.bulletProfiles, locale),
        t(R.featureVoiceClone.bulletTimbre, locale),
        t(R.featureVoiceClone.bulletVoiceLyrics, locale),
        genPerMonthStudio(locale, studioLimit),
      ],
      primaryLabel: t(C.goStudio, locale),
      secondaryLabel: t(R.featureVoiceToSong.keepTrial, locale),
      targetPlan: "studio",
    };
  }

  if (reason === "feature_priority") {
    const targetPriority = priorityUpsellTarget(plan);
    return {
      title: t(R.featurePriority.title, locale),
      description:
        cur === "free" ? t(R.featurePriority.descFree, locale) : t(R.featurePriority.descPaid, locale),
      bullets:
        targetPriority === "pro"
          ? [
              genPerMonth(locale, proLimit),
              t(R.featurePriority.bulletPriorityFree, locale),
              t(R.featurePriority.bulletMp3Commercial, locale),
              planPriceUpsellLabel("pro", locale),
            ]
          : [
              genPerMonth(locale, plusLimit),
              t(R.featurePriority.bulletMaxPriority, locale),
              t(R.featurePriority.bulletPermanentAudio, locale),
              t(R.featurePriority.bulletStemsZip, locale),
            ],
      primaryLabel: targetPriority === "pro" ? goProLabel(locale) : goPlusLabel(locale),
      secondaryLabel: t(C.tryAgainLater, locale),
      targetPlan: targetPriority,
    };
  }

  if (reason === "feature_stems") {
    return {
      title: t(R.featureStems.title, locale),
      description: t(R.featureStems.description, locale),
      bullets: [
        genPerMonth(locale, plusLimit),
        t(R.featureStems.bulletStemsPerTrack, locale),
        t(R.featurePriority.bulletPermanentAudio, locale),
        planPriceUpsellLabel("plus", locale),
      ],
      primaryLabel: goPlusLabel(locale),
      secondaryLabel: t(C.notNow, locale),
      targetPlan: "plus",
    };
  }

  if (reason === "feature_no_watermark") {
    return {
      title: t(R.featureNoWatermark.title, locale),
      description: t(R.featureNoWatermark.description, locale),
      bullets: [
        t(R.featureNoWatermark.bulletNoWatermark, locale),
        t(R.featureNoWatermark.bulletCommercialRights, locale),
        genShortPerMonth(locale, proLimit),
        planPriceUpsellLabel("pro", locale),
      ],
      primaryLabel: goProLabel(locale),
      secondaryLabel: t(R.featureNoWatermark.keepWatermark, locale),
      targetPlan: "pro",
    };
  }

  if (reason === "feature_permanent_audio") {
    const targetAudio: PaidPlanId = cur === "free" ? "pro" : "plus";
    return {
      title: t(R.featurePermanentAudio.title, locale),
      description:
        cur === "free"
          ? t(R.featurePermanentAudio.descFree, locale)
          : t(R.featurePermanentAudio.descPaid, locale),
      bullets:
        targetAudio === "pro"
          ? [
              i(t(R.featurePermanentAudio.bulletHostingDays, locale), { days: LOOP_AUDIO_RETENTION_DAYS_PRO }),
              genShortPerMonth(locale, proLimit),
              t(R.featurePermanentAudio.bulletWavExport, locale),
              planPriceUpsellLabel("pro", locale),
            ]
          : [
              t(R.featurePermanentAudio.bulletPermanentHosting, locale),
              t(R.featurePermanentAudio.bulletStemsZip, locale),
              genShortPerMonth(locale, plusLimit),
              planPriceUpsellLabel("plus", locale),
            ],
      primaryLabel: primaryForTarget(locale, targetAudio),
      secondaryLabel: t(C.openLibrary, locale),
      targetPlan: targetAudio,
    };
  }

  if (reason === "feature_producer_tag") {
    return {
      title: t(R.featureProducerTag.title, locale),
      description: t(R.featureProducerTag.description, locale),
      bullets: [
        t(R.featureProducerTag.bulletUpload, locale),
        t(R.featureProducerTag.bulletApply, locale),
        genPerMonth(locale, proLimit),
        planPriceUpsellLabel("pro", locale),
      ],
      primaryLabel: goProLabel(locale),
      secondaryLabel: t(R.featureProducerTag.keepFree, locale),
      targetPlan: "pro",
    };
  }

  if (reason === "feature_commercial_download") {
    return {
      title: t(R.featureCommercialDownload.title, locale),
      description: commercialRightsFaq(locale).a,
      bullets: [
        i(t(R.postGeneration.bulletProGen, locale), { n: proLimit }),
        t(R.featureCommercialDownload.bulletPlatforms, locale),
        t(R.featurePermanentAudio.bulletWavExport, locale),
        planPriceUpsellLabel("pro", locale),
      ],
      primaryLabel: goProLabel(locale),
      secondaryLabel: t(R.featureCommercialDownload.personalOnly, locale),
      targetPlan: "pro",
    };
  }

  if (reason === "credits_low") {
    const label = planDisplayName(cur);
    if (cur !== "free") {
      return {
        title: t(R.creditsLow.titleAlmost, locale),
        description: i(t(R.creditsLow.planRemaining, locale), {
          plan: label,
          limit: baseLimit,
          remaining: generationsRemaining(locale, remaining),
        }),
        bullets:
          target === "plus"
            ? [
                genPerMonthPlus(locale, PLAN_LIMITS.plus),
                t(R.featurePriority.bulletPermanentAudio, locale),
                t(R.creditsLow.bulletSeparateStems, locale),
              ]
            : [
                genPerMonthStudio(locale, studioLimit),
                t(R.creditsLow.bulletMasteredWav, locale),
                t(R.featureDualGeneration.bulletAllPro, locale),
              ],
        primaryLabel: target ? primaryForTarget(locale, target) : t(C.viewPricing, locale),
        secondaryLabel: t(C.close, locale),
        targetPlan: target,
      };
    }
    return {
      title: creditsLowFreeTitle(locale, remaining),
      description: i(t(R.creditsLow.descFree, locale), { limit: baseLimit, proLimit }),
      bullets: [
        genPerMonth(locale, proLimit),
        t(R.creditsLow.bulletPriority, locale),
        t(R.creditsLow.bulletSongRemix, locale),
        t(R.creditsLow.bulletMp3Royalty, locale),
      ],
      primaryLabel: goProLabel(locale),
      secondaryLabel: t(C.notNow, locale),
      targetPlan: "pro",
    };
  }

  if (reason === "post_generation") {
    if (cur !== "free") {
      return buildUpsellCopy("limit_reached", locale, plan, ctx);
    }
    return {
      title: t(R.postGeneration.title, locale),
      description: i(t(R.postGeneration.description, locale), { limit: baseLimit }),
      bullets: [
        i(t(R.postGeneration.bulletProGen, locale), { n: proLimit }),
        t(R.postGeneration.bulletPriorityQueue, locale),
        t(R.creditsLow.bulletSongRemix, locale),
        t(R.postGeneration.bulletMoreBonuses, locale),
      ],
      primaryLabel: t(C.goPro, locale),
      secondaryLabel: t(R.postGeneration.keepFree, locale),
      targetPlan: "pro",
    };
  }

  if (cur !== "free" && !target) {
    const isQuotaExhausted = reason === "credits_exhausted" || reason === "limit_reached";
    if (isQuotaExhausted) {
      return {
        title: t(R.exhausted.title, locale),
        description: t(R.quotaMax.description, locale),
        bullets: [
          t(R.quotaMax.bulletBonusesTomorrow, locale),
          t(R.quotaMax.bulletReferrals, locale),
          t(R.quotaMax.bulletLibraryKept, locale),
        ],
        primaryLabel: getCreditPackCtaLabel(locale),
        secondaryLabel: t(C.close, locale),
        targetPlan: null,
      };
    }
    return {
      title: t(R.quotaMax.title, locale),
      description: t(R.quotaMax.description, locale),
      bullets: [
        t(R.quotaMax.bulletBonusesTomorrow, locale),
        t(R.quotaMax.bulletReferrals, locale),
        t(R.quotaMax.bulletLibraryKept, locale),
      ],
      primaryLabel: t(C.settingsBilling, locale),
      secondaryLabel: t(C.close, locale),
      targetPlan: null,
    };
  }

  const exhaustedDesc =
    cur === "free"
      ? i(t(R.exhausted.descFree, locale), {
          used: ctx.usedThisMonth ?? baseLimit,
          total: ctx.totalLimit ?? baseLimit,
          proLimit,
        })
      : target
        ? i(t(R.exhausted.descPaid, locale), { plan: cur, target: planName(target) })
        : i(t(R.exhausted.descPaidFallback, locale), { plan: cur });

  return {
    title:
      reason === "limit_reached"
        ? t(R.exhausted.limitReachedTitle, locale)
        : t(R.exhausted.title, locale),
    description: exhaustedDesc,
    bullets:
      target === "pro"
        ? [
            genPerMonth(locale, proLimit),
            t(R.exhausted.bulletPriorityVsFree, locale),
            t(R.exhausted.bulletSongRemixStudio, locale),
            planPriceUpsellLabel("pro", locale),
          ]
        : target === "studio"
          ? [
              genPerMonth(locale, studioLimit),
              t(R.featureDualGeneration.bulletParallel, locale),
              t(R.creditsLow.bulletMasteredWav, locale),
              planPriceUpsellLabel("studio", locale),
            ]
          : target === "plus"
            ? [
                i(t(R.exhausted.bulletPlusVsStudio, locale), { plus: plusLimit, studio: studioLimit }),
                t(R.featurePriority.bulletPermanentAudio, locale),
                t(R.exhausted.bulletStemsFast, locale),
                t(R.exhausted.bulletKeepCreating, locale),
              ]
            : [
                t(R.exhausted.bulletBonusesTomorrow, locale),
                t(R.exhausted.bulletInviteFriends, locale),
                t(R.exhausted.bulletTracksStay, locale),
              ],
    primaryLabel: target ? primaryForTarget(locale, target) : t(C.viewPricing, locale),
    secondaryLabel: t(C.close, locale),
    targetPlan: target,
  };
}

