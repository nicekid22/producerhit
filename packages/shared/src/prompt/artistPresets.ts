// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type ArtistRegion = "fr" | "us";

export interface ArtistPreset {
  /** Unique slug e.g. "sza", "tiakola" */
  id: string;
  /** Display name e.g. "SZA-inspired", "Tiakola-inspired" */
  display: string;
  /** Full artist name */
  artistName: string;
  /** Region / catalog */
  region: ArtistRegion;
  /** Primary genre tag */
  genre: string;
  /** ACE-Step caption — prose description of the sonic world */
  caption: string;
  /** Recommended BPM (will be sent in audioConfig) */
  bpm: number;
  /** Recommended key */
  key: string;
  /** Scale */
  scale: string;
  /** Time signature */
  timeSignature: string;
  /** Recommended duration in seconds */
  duration: number;
  /** Vocal language code */
  vocalLanguage: string;
  /** Vocal style direction */
  vocalStyle: string;
  /** Chips / tags for quick search */
  tags: readonly string[];
}

