export const ALL_ARTIST_PRESETS: readonly ArtistPreset[] = [...FR_PRESETS, ...US_PRESETS];

/** French presets only */
export const FR_ARTIST_PRESETS: readonly ArtistPreset[] = FR_PRESETS;

/** US presets only */
export const US_ARTIST_PRESETS: readonly ArtistPreset[] = US_PRESETS;

// ---------------------------------------------------------------------------
// Lookup helpers
// ---------------------------------------------------------------------------

/** Find a preset by id (slug) */
export function findArtistPresetById(id: string): ArtistPreset | undefined {
  return ALL_ARTIST_PRESETS.find((p) => p.id === id);
}

/** Find a preset by display name (case-insensitive) */
export function findArtistPresetByDisplay(display: string): ArtistPreset | undefined {
  const lower = display.trim().toLowerCase();
  return ALL_ARTIST_PRESETS.find((p) => p.display.toLowerCase() === lower);
}

/** Filter presets by region */
export function getArtistPresetsByRegion(region: ArtistRegion): readonly ArtistPreset[] {
  return region === "fr" ? FR_ARTIST_PRESETS : US_ARTIST_PRESETS;
}

/** Search presets by tag or name (case-insensitive) */
export function searchArtistPresets(query: string): readonly ArtistPreset[] {
  const lower = query.trim().toLowerCase();
  if (!lower) return ALL_ARTIST_PRESETS;
  return ALL_ARTIST_PRESETS.filter(
    (p) =>
      p.artistName.toLowerCase().includes(lower) ||
      p.genre.toLowerCase().includes(lower) ||
      p.tags.some((t) => t.includes(lower)),
  );
}

/** Build the ACE-Step caption from a preset (ready for prompt injection) */
export function buildArtistPresetCaption(preset: ArtistPreset): string {
  return preset.caption;
}
